//! macOS pasteboard access for the paste path: capture everything on the
//! general pasteboard, lend it to one transcript, then put it back.
//!
//! Every function takes the pasteboard so tests can run against a private,
//! uniquely named one instead of the user's clipboard.

use objc2::rc::Retained;
use objc2::runtime::{NSObjectProtocol, ProtocolObject};
use objc2::{msg_send, sel};
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardWriting};
use objc2_foundation::{NSArray, NSData, NSString};

/// One entry per pasteboard item; each item is its `(type, bytes)` pairs.
pub type Items = Vec<Vec<(String, Vec<u8>)>>;

const PLAIN_TEXT: &str = "public.utf8-plain-text";

/// Markers from the nspasteboard.org convention. Clipboard managers skip an
/// entry that carries them, so the transcript stays out of clipboard history.
const SKIP_HISTORY_MARKERS: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

pub fn general() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

/// `NSPasteboardAccessBehavior` values under which reading the pasteboard
/// shows a permission alert (ask) or is refused (always deny).
const ACCESS_ASK: isize = 1;
const ACCESS_ALWAYS_DENY: isize = 3;

/// Whether the pasteboard can be read without macOS interrupting the user.
/// The property exists from macOS 15.4; older systems always allow reads.
fn reads_allowed(pasteboard: &NSPasteboard) -> bool {
    if !pasteboard.respondsToSelector(sel!(accessBehavior)) {
        return true;
    }
    let behavior: isize = unsafe { msg_send![pasteboard, accessBehavior] };
    behavior != ACCESS_ASK && behavior != ACCESS_ALWAYS_DENY
}

/// Copy out every item and every representation it offers. `None` means the
/// contents could not be read, so there is nothing safe to restore.
pub fn snapshot(pasteboard: &NSPasteboard) -> Option<Items> {
    if !reads_allowed(pasteboard) {
        return None;
    }
    let items = pasteboard.pasteboardItems()?;
    Some(
        items
            .iter()
            .map(|item| {
                item.types()
                    .iter()
                    .filter_map(|data_type| {
                        item.dataForType(&data_type)
                            .map(|data| (data_type.to_string(), data.to_vec()))
                    })
                    .collect()
            })
            .collect(),
    )
}

/// Replace the pasteboard with `text`, flagged so clipboard managers do not
/// record it.
pub fn write_transient_text(pasteboard: &NSPasteboard, text: &str) -> Result<(), String> {
    pasteboard.clearContents();
    if !pasteboard.setString_forType(&NSString::from_str(text), &NSString::from_str(PLAIN_TEXT)) {
        return Err("could not write the transcript to the clipboard".to_string());
    }
    let empty = NSData::with_bytes(&[]);
    for marker in SKIP_HISTORY_MARKERS {
        pasteboard.setData_forType(Some(&empty), &NSString::from_str(marker));
    }
    Ok(())
}

/// Put a snapshot back, replacing whatever is on the pasteboard now.
pub fn restore(pasteboard: &NSPasteboard, items: &Items) -> Result<(), String> {
    pasteboard.clearContents();
    if items.is_empty() {
        return Ok(());
    }
    let objects: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = items
        .iter()
        .map(|representations| {
            let item = NSPasteboardItem::new();
            for (data_type, bytes) in representations {
                item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(data_type));
            }
            ProtocolObject::from_retained(item)
        })
        .collect();
    if pasteboard.writeObjects(&NSArray::from_retained_slice(&objects)) {
        Ok(())
    } else {
        Err("could not restore the previous clipboard contents".to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A private pasteboard, so these tests never touch the user's clipboard.
    struct Scratch(Retained<NSPasteboard>);

    impl Scratch {
        fn new() -> Self {
            Self(NSPasteboard::pasteboardWithUniqueName())
        }
    }

    impl Drop for Scratch {
        fn drop(&mut self) {
            // Free the named pasteboard in the pasteboard server.
            let _: () = unsafe { msg_send![&*self.0, releaseGlobally] };
        }
    }

    fn types_of(pasteboard: &NSPasteboard) -> Vec<String> {
        pasteboard
            .types()
            .map(|types| types.iter().map(|t| t.to_string()).collect())
            .unwrap_or_default()
    }

    fn string_of(pasteboard: &NSPasteboard) -> Option<String> {
        pasteboard
            .stringForType(&NSString::from_str(PLAIN_TEXT))
            .map(|s| s.to_string())
    }

    #[test]
    fn transient_text_is_readable_and_flagged_for_clipboard_managers() {
        let scratch = Scratch::new();
        write_transient_text(&scratch.0, "dictated words").unwrap();

        assert_eq!(string_of(&scratch.0).as_deref(), Some("dictated words"));
        let types = types_of(&scratch.0);
        for marker in SKIP_HISTORY_MARKERS {
            assert!(types.iter().any(|t| t == marker), "missing {marker}");
        }
    }

    #[test]
    fn restore_brings_back_every_representation_of_the_original() {
        let scratch = Scratch::new();
        let original: Items = vec![vec![
            (PLAIN_TEXT.to_string(), b"copied earlier".to_vec()),
            ("public.html".to_string(), b"<b>copied earlier</b>".to_vec()),
            ("com.example.custom".to_string(), vec![0, 159, 146, 150]),
        ]];
        restore(&scratch.0, &original).unwrap();

        let saved = snapshot(&scratch.0).expect("readable pasteboard");
        write_transient_text(&scratch.0, "dictated words").unwrap();
        restore(&scratch.0, &saved).unwrap();

        assert_eq!(snapshot(&scratch.0), Some(original));
        assert!(!types_of(&scratch.0)
            .iter()
            .any(|t| SKIP_HISTORY_MARKERS.contains(&t.as_str())));
    }

    #[test]
    fn restoring_an_empty_snapshot_leaves_the_pasteboard_empty() {
        let scratch = Scratch::new();
        let saved = snapshot(&scratch.0).expect("readable pasteboard");
        assert!(saved.is_empty());

        write_transient_text(&scratch.0, "dictated words").unwrap();
        restore(&scratch.0, &saved).unwrap();

        assert_eq!(string_of(&scratch.0), None);
    }

    #[test]
    fn several_items_survive_a_round_trip() {
        let scratch = Scratch::new();
        let original: Items = vec![
            vec![("public.file-url".to_string(), b"file:///tmp/a.txt".to_vec())],
            vec![("public.file-url".to_string(), b"file:///tmp/b.txt".to_vec())],
        ];
        restore(&scratch.0, &original).unwrap();
        assert_eq!(snapshot(&scratch.0), Some(original));
    }
}
